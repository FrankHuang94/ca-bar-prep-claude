#!/usr/bin/env python3
"""Monthly maintenance (Phase 8): where should the question bank grow?

Reads 10-progress/attempts.csv and the bank, then reports:
  * MBE topics where you are weak: at least --min-attempts MCQ attempts (repo or licensed) and
    accuracy below --threshold. For each, the number of fresh bank questions left on that topic
    (never attempted and not reserved for an unsat simulation). A weak topic with fewer than
    --min-fresh fresh questions is an EXPANSION TARGET: write new items there.
  * Essay subjects whose average score is below --essay-target, with the fresh essays left.
  * A bank inventory per subject (total, fresh, reserved), useful even before any attempts.

Topics are coverage rows cut to two outline levels (EVD-MBE-V.F.2 -> EVD-MBE-V.F), so a weak
area collects enough attempts to mean something. Thresholds default to the current checkpoint
in config/plan.yml (the first benchmark whose date has not passed).

Usage
  python scripts/bank_targets.py
  python scripts/bank_targets.py --threshold 0.62 --min-attempts 5 --min-fresh 10 --essay-target 62
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from collections import defaultdict

import common as C


def topic(cid: str) -> str:
    parts = cid.split("-", 2)
    if len(parts) < 3:
        return cid
    ref = ".".join(parts[2].split(".")[:2])
    return f"{parts[0]}-{parts[1]}-{ref}"


def current_benchmark(today: dt.date | None = None) -> dict:
    today = today or dt.date.today()
    marks = (C.load_plan() or {}).get("benchmarks") or []
    for b in marks:
        by = b.get("by")
        by = by if isinstance(by, dt.date) else dt.date.fromisoformat(str(by))
        if by >= today:
            return b
    return marks[-1] if marks else {}


def analyse(threshold: float, min_attempts: int, min_fresh: int, essay_target: float) -> str:
    attempts = C.load_attempts()
    reserved = C.reserved_sim_items()
    mcqs = C.load_mcqs()
    essays = [e for e in C.load_md_items(C.ESSAY_DIR_REL) if e["_fm"].get("id")]
    seen = {a["item_id"] for a in attempts}

    # bank by topic: fresh = never attempted and not reserved
    bank_fresh: dict[str, int] = defaultdict(int)
    inv: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])  # total, fresh, reserved
    for q in mcqs:
        s = q.get("subject", "?")
        inv[s][0] += 1
        if q["id"] in reserved:
            inv[s][2] += 1
            continue
        if q["id"] not in seen:
            inv[s][1] += 1
            for t in {topic(c) for c in q.get("coverage_ids") or []}:
                bank_fresh[t] += 1

    # MCQ performance by topic (repo and licensed questions alike)
    perf: dict[str, list[int]] = defaultdict(list)
    for a in attempts:
        if a["kind"] != "mcq" or a["correct"] not in ("Y", "N"):
            continue
        for t in {topic(c) for c in C.split_list(a["coverage_ids"])}:
            perf[t].append(1 if a["correct"] == "Y" else 0)

    out = [f"_Generated by `scripts/bank_targets.py` on {C.today()}: weak-topic threshold "
           f"{threshold:.0%} with at least {min_attempts} attempts; expansion target when fewer than "
           f"{min_fresh} fresh questions remain._", "", "### Weak MBE topics", ""]
    weak = sorted(((t, sum(v) / len(v), len(v)) for t, v in perf.items()
                   if len(v) >= min_attempts and sum(v) / len(v) < threshold), key=lambda x: x[1])
    if not perf:
        out.append("No MCQ attempts logged yet, so there is no weak-area signal. Log practice with "
                   "`quiz.py log` (licensed questions with `--source official --coverage ...`).")
    elif not weak:
        out.append("No topic is below the threshold with enough attempts.")
    else:
        out += ["| Topic | Attempts | Accuracy | Fresh bank questions | Action |", "|---|---|---|---|---|"]
        for t, acc, n in weak:
            fresh = bank_fresh.get(t, 0)
            action = f"**EXPAND: write {min_fresh - fresh}+ new items**" if fresh < min_fresh else "practice the fresh items"
            out.append(f"| {t} | {n} | {acc:.0%} | {fresh} | {action} |")

    out += ["", "### Essay subjects below target", ""]
    scores: dict[str, list[float]] = defaultdict(list)
    for a in attempts:
        if a["kind"] == "essay" and a["score"]:
            scores[a["subject"]].append(float(a["score"]))
    low = sorted(((s, sum(v) / len(v), len(v)) for s, v in scores.items() if sum(v) / len(v) < essay_target),
                 key=lambda x: x[1])
    if not scores:
        out.append("No essay attempts logged yet.")
    elif not low:
        out.append(f"Every essay subject averages {essay_target:.0f} or more.")
    else:
        out += ["| Subject | Essays graded | Average | Fresh essays in the bank | Action |", "|---|---|---|---|---|"]
        for s, avg, n in low:
            fresh = sum(1 for e in essays if s in (e["_fm"].get("subjects") or [e["_fm"].get("subject")])
                        and e["_fm"]["id"] not in seen and e["_fm"]["id"] not in reserved)
            action = "**EXPAND: write 2 new essays**" if fresh < 3 else "practice the fresh essays"
            out.append(f"| {s} | {n} | {avg:.0f} | {fresh} | {action} |")

    out += ["", "### Bank inventory (MCQs)", "", "| Subject | Total | Fresh | Reserved for simulations |",
            "|---|---|---|---|"]
    for s in sorted(inv):
        t, f, r = inv[s]
        out.append(f"| {s} | {t} | {f} | {r} |")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    bm = current_benchmark()
    ap = argparse.ArgumentParser(description="Question-bank expansion targets from attempts.csv.")
    ap.add_argument("--threshold", type=float, default=float(bm.get("mbe_accuracy", 0.62)))
    ap.add_argument("--min-attempts", type=int, default=5)
    ap.add_argument("--min-fresh", type=int, default=10)
    ap.add_argument("--essay-target", type=float, default=float(bm.get("essay_avg", 62)))
    a = ap.parse_args(argv)
    print(analyse(a.threshold, a.min_attempts, a.min_fresh, a.essay_target))
    return 0


if __name__ == "__main__":
    sys.exit(main())
