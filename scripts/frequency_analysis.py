#!/usr/bin/env python3
"""Past-exam frequency analysis from 06-past-exams/index.csv.

Produces (between <!-- BEGIN GENERATED-FREQUENCY --> markers in 06-past-exams/frequency-analysis.md):
  * subject x administration heatmap (essays only; crossovers count for every subject they include)
  * subject totals, share of essays, last time tested, administrations since last tested
  * top issues per subject (coverage_id counts, with matrix headings)
  * crossover pairs
  * PT task types and areas (04-performance-test/past-pt-index.csv)

Usage
  python scripts/frequency_analysis.py            # rewrite the generated block
  python scripts/frequency_analysis.py --stdout   # print only
  python scripts/frequency_analysis.py --since 2015-02 --top 8

Caveat (repeated in the output): past frequency is a guide, not a prediction. The State Bar
does not announce which subjects will appear, and every subject remains testable.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from itertools import combinations

import common as C

MARKER = "GENERATED-FREQUENCY"


def exam_key(e: str) -> tuple[int, int]:
    y, m = e.split("-")
    return int(y), int(m)


def analyse(since: str | None, top: int) -> str:
    rows = [r for r in C.read_csv(C.p(C.PAST_INDEX_REL)) if r["type"] == "essay"]
    if since:
        rows = [r for r in rows if exam_key(r["exam"]) >= exam_key(since)]
    if not rows:
        return "_No essay rows in 06-past-exams/index.csv yet (filled in Phase 3)._"
    headings = {r["coverage_id"]: r["heading"] for r in C.load_matrix()}
    exams = sorted({r["exam"] for r in rows}, key=exam_key)
    grid: dict[str, Counter] = defaultdict(Counter)
    issues: dict[str, Counter] = defaultdict(Counter)
    pairs: Counter = Counter()
    for r in rows:
        subs = C.split_list(r["subjects"])
        for s in subs:
            grid[s][r["exam"]] += 1
        for a, b in combinations(sorted(set(subs)), 2):
            pairs[(a, b)] += 1
        for cid in C.split_list(r["issues"]):
            issues[cid.split("-")[0]][cid] += 1
    n_q = len(rows)
    out = [f"_Generated by `scripts/frequency_analysis.py` on {C.today()} from {n_q} essay questions across "
           f"{len(exams)} administrations ({exams[0]} → {exams[-1]})._", "",
           "> Past frequency is a guide to emphasis, not a prediction. Every subject on the scope list remains testable.",
           "", "### Subject totals and recency", "",
           "| Subject | Essays tested | Share of essays | Administrations with subject | Last tested | Administrations since |",
           "|---|---|---|---|---|---|"]
    order = sorted(C.SUBJECTS, key=lambda c: -sum(grid[c].values()))
    for c in order:
        tot = sum(grid[c].values())
        present = [e for e in exams if grid[c][e]]
        last = present[-1] if present else "—"
        since_n = (len(exams) - 1 - exams.index(last)) if present else len(exams)
        out.append(f"| {C.SUBJECTS[c].name} | {tot} | {100 * tot / n_q:.0f}% | {len(present)}/{len(exams)} | {last} | {since_n} |")
    out += ["", "### Heatmap (essays per administration; ■ = 1, ■■ = 2)", "",
            "| Subject | " + " | ".join(e.replace("-0", "-").replace("20", "'", 1) for e in exams) + " |",
            "|---|" + "---|" * len(exams)]
    for c in order:
        out.append(f"| {c} | " + " | ".join("■" * grid[c][e] if grid[c][e] else "·" for e in exams) + " |")
    out += ["", "### Most-tested issues by subject", ""]
    for c in order:
        if not issues[c]:
            continue
        out.append(f"**{C.SUBJECTS[c].name}**")
        for cid, n in issues[c].most_common(top):
            out.append(f"- {cid} — {headings.get(cid, '(not in matrix)')[:80]} — {n}×")
        out.append("")
    out += ["### Crossover pairs", "", "| Pair | Times |", "|---|---|"]
    for (a, b), n in pairs.most_common(15):
        out.append(f"| {C.SUBJECTS[a].name} + {C.SUBJECTS[b].name} | {n} |")
    pts = C.read_csv(C.p(C.PAST_PT_INDEX_REL))
    if pts:
        out += ["", "### Performance Tests", "", "| Task type | Count |", "|---|---|"]
        for t, n in Counter(r["task_type"] for r in pts).most_common():
            out.append(f"| {t} | {n} |")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Past-exam frequency analysis.")
    ap.add_argument("--stdout", action="store_true")
    ap.add_argument("--since", help="first administration to include, e.g. 2015-02")
    ap.add_argument("--top", type=int, default=10)
    a = ap.parse_args(argv)
    block = analyse(a.since, a.top)
    if a.stdout:
        print(block)
        return 0
    path = C.p(C.FREQ_REL)
    if path.exists():
        text = path.read_text(encoding="utf-8")
    else:
        text = ("---\nsubject: past-exams\ntopic: Past-exam frequency analysis\ncoverage_ids: []\n"
                "tested_on: [essay, PT]\nexam_frequency: {level: n/a, basis: \"Analysis file\"}\n"
                f"last_verified: {C.today()}\nstatus: draft\n---\n\n# Past-exam frequency analysis\n")
    path.write_text(C.replace_between_markers(text, MARKER, block), encoding="utf-8")
    print(f"updated {C.FREQ_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
